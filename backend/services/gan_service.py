from typing import Dict, Any
from PIL import Image
from models.gan_model import MangoCGANModel
from models.class_registry import GAN_SUPPORTED_FRUITS

cgan_model = MangoCGANModel()

def simulate_future_stage(image: Image.Image, temperature: float, target_stage: str, fruit: str = "mango") -> Dict[str, Any]:
    """
    Primary API handler for POST /api/simulate and POST /api/generate-twin.
    Synthesizes target stage visual image using Conditional GAN generator where trained,
    or honestly discloses that GAN simulation is unavailable for uncalibrated fruit classes.
    """
    fruit_lower = fruit.lower()
    if fruit_lower not in GAN_SUPPORTED_FRUITS:
        return {
            "fruit": fruit,
            "is_supported": False,
            "model_connected": False,
            "target_stage": target_stage,
            "generated_image": None,
            "status_message": f"GAN future appearance simulation is not yet trained or calibrated for {fruit.capitalize()}. Supported fruits: Mango, Banana, Apple, Papaya."
        }

    gen_b64 = cgan_model.generate_future_stage(image, target_stage)
    
    if gen_b64:
        return {
            "fruit": fruit,
            "is_supported": True,
            "model_connected": True,
            "target_stage": target_stage,
            "generated_image": gen_b64,
            "status_message": f"Future appearance generated by Conditional GAN for {fruit.upper()} ({target_stage} stage)."
        }
    else:
        return {
            "fruit": fruit,
            "is_supported": False,
            "model_connected": False,
            "target_stage": target_stage,
            "generated_image": None,
            "status_message": f"GAN model execution encountered an issue for {fruit}."
        }
